similarity_instruction = (
    "You are an evaluator for a video question answering system. Your task is to rate the whether the predicted answer covers the key points of the ground truth answer. Use the following scale to assign a score:\n"
    "- 3: Mostly covered; the predicted answer covers all key information in the ground truth answer, though it may have minor inaccuracies or rephrases.\n"
    "- 2: Partially covered; the predicted answer has some correct information, but also contains significant inaccuracies or missing key points.\n"
    "- 1: Incorrect; the predicted answer may be related to the ground truth answer, but most of the information is missing, or the predicted answer is not relevant to the question or in very poor quality."
    "Output the score only, do not add more explanations."
)

repetition_instruction = (
    "You are an evaluator for a multi-turn video question answering system. Your task is to judge whether a newr reply generated by the model is repetitive (all its information is already convered by previous turns) or not.\n"
    "Output \"yes\" if all information in the new turn is already covered by previous turns. Output \"no\" if there is new information in the new turn.\n"
    "Since you are judging a visual question answering system, When judging what information a sentence contains, only consider visible content, and ignore invisible content such as the conjectures and inferences.\n"
    "Only reply with \"yes\" or \"no\". Do not add any more explainations."
)


def calculate_similarity_score(question, pred, gold):
    model_input = (
        f"Question: {question}\n"
        f"Ground Truth Answer: {gold}\n"
        f"Predicted Answer: {pred}\n"
    )
    if 'Qwen3' in MODEL:
        model_input += "/no_think"     # non-thinking mode for qwen-3

    data = {
        "model": MODEL,
        "messages": [
            {'role': 'system', 'content': similarity_instruction},
            {'role': 'user', 'content': model_input},
        ],
    }

    if "gemini-2.5" in MODEL:
        data['reasoning_effort'] = 'low'
    if API_KEY is not None:
        headers = {'Authorization': f'Bearer {API_KEY}', 'Content-Type': 'application/json'}
    else:
        headers = None

    # debug print
    if random.random() < 0.1:
        print(f"sending data to LLM: {data}")

    retry_times = 3
    score = 0
    while retry_times > 0:
        if 'gpt' in MODEL:
            time.sleep(2)
        try:
            response = requests.post(URL, json=data, headers=headers)
            response.raise_for_status()
            model_output = response.json()['choices'][0]['message']['content']
            model_output = model_output.replace('<think>', '').replace('</think>', '').strip()
            if model_output in ['3', '2', '1']:
                score = int(model_output) - 1
                retry_times = 0
            else:
                raise ValueError("model output must be numbers!")
        except Exception as e:
            print(f"Error in calculate_similarity_score: {e}")
            time.sleep(1.5)
            retry_times -= 1
    return score


def calculate_is_repetition(previous_sents, pred_sent):
    model_input = (
        f"Previous Turns: {previous_sents}\n"
        f"New Turn: {pred_sent}\n"
    )
    if "Qwen3" in MODEL:
        model_input += "/no_think"     # non-thinking mode for qwen-3

    data = {
        "model": MODEL,
        "messages": [
            {'role': 'system', 'content': repetition_instruction},
            {'role': 'user', 'content': model_input},
        ],
    }

    if "gemini-2.5" in MODEL:
        data['reasoning_effort'] = 'low'

    if API_KEY is not None:
        headers = {'Authorization': f'Bearer {API_KEY}', 'Content-Type': 'application/json'}
    else:
        headers = None

    # debug print
    if random.random() < 0.1:
        print(f"sending data to LLM: {data}")

    retry_times = 3
    res = False
    while retry_times > 0:
        if 'gpt' in MODEL:
            time.sleep(1.5)
        try:
            response = requests.post(URL, json=data, headers=headers)
            response.raise_for_status()
            model_output = response.json()['choices'][0]['message']['content']
            model_output = model_output.replace('<think>', '').replace('</think>', '').strip()
            res = model_output.lower().startswith('yes')
            retry_times = 0
        except Exception as e:
            print(f"Error in calculate_is_repetition: {e}")
            time.sleep(1.5)
            retry_times -= 1
    return res


def process_example(data):
    question_id, pred_data, ground_truth, is_single_question = data
    max_score = 2

    user_data = [turn for turn in pred_data if turn['role'] == 'user' and turn.get('time', None) is not None]
    pred_data = [turn for turn in pred_data if turn['role'] == 'assistant' and turn.get('time', None) is not None]
    
    pred_data = [[data['time'], data['content'].replace('<|im_end|>', '').strip()] for data in pred_data]
    questions_list = [turn for turn in ground_truth['conversation'] if turn['role'] == 'user']

    res_list = list()
    for answer_turn in ground_truth['answer']:
        turn_res_list = list()

        # Find the last question before the end of reply_timespan. This is the question corresponding to this ground truth turn.
        if not is_single_question:
            question_idx = 0
            while question_idx < len(questions_list) - 1 and questions_list[question_idx]['time'] < answer_turn['reply_timespan'][1]:
                question_idx += 1
            if question_idx >= len(user_data):
                print(f"Error: question_idx >= len(user_data), {question_idx=}, {user_data=}, {questions_list=}")
        else:
            for question_idx in range(len(questions_list)):
                if questions_list[question_idx]['role'] == 'user':
                    break
        question, question_time = questions_list[question_idx]['content'], questions_list[question_idx]['time']

        if answer_turn['reply_timespan'][1] - answer_turn['reply_timespan'][0] < 0.5:
            # this is a immediate reply.
            # Check when the corresponding question was actually raised during the real inference process, and switch reply_timespan to the actual raising time of this question.
            # print(f"this is a immediate reply: \n{answer_turn=}\n{questions_list[question_idx]=}\n{user_data[question_idx]=}")
            real_question_time_during_inference = user_data[question_idx]['time']
            answer_turn['reply_timespan'] = [real_question_time_during_inference, real_question_time_during_inference]

        all_pred_sents = [(time, pred_sent) for time, pred_sent in pred_data \
                    if answer_turn['reply_timespan'][0] <= time <= answer_turn['reply_timespan'][1]]

        added_pred_sents = []
        for pred_time, pred_sent in all_pred_sents:
            if pred_sent == NO_REPLY_STR: continue
            if pred_sent in added_pred_sents:
                turn_res_list.append({'time': pred_time, 'content': pred_sent, 'score': turn_res_list[-1]['score'], 'repetition': True})
                continue
            added_pred_sents.append(pred_sent)
            score = calculate_similarity_score(question, ' '.join(added_pred_sents), answer_turn['content'])
            if len(added_pred_sents) != 1:
                is_repetition = calculate_is_repetition(' '.join(added_pred_sents[:-1]), pred_sent)
            else:
                is_repetition = False
            turn_res_list.append({'time': pred_time, 'content': pred_sent, 'score': score, 'repetition': is_repetition})
        res_list.append(turn_res_list)
    ret = {'question_id': question_id, 'res_list': res_list}
    return ret


def area_under_line_ratio(points, max_x, max_y, floor_time_score_weight=0.5, start_score=0.5):
    """
    Calculate the area under the polyline formed by coordinate points and the x-axis
    Note that adjacent points are not connected by a straight line; instead, at the next point x_2, the y value suddenly jumps to y_2.

    :param points: list containing (x, y) tuples, e.g. [(x1, y1), (x2, y2), ...]
    :return: area (float)
    """
    if not len(points): return start_score / max_y
    points = sorted(points, key=lambda p: p[0])  # Sort by x coordinate (ensure calculation from left to right)

    # Even if I generate a reply at the end of the span, it is considered to have obtained `floor_time_score_weight=0.5` of all time score.
    # Otherwise, if the model happens to generate a reply at the very end of the span, the time score would be almost 0, which would make the overall score almost 0.
    # And this answer generated near the end of the span is obviously valuable.
    # If this hyperparameter is 0, the x-axis is not modified, which is a scenario where timeliness is more important than correctness.
    # If this hyperparameter is 1, all points are shifted to 1 on the x-axis. This is a scenario where correctness is more important than timeliness.

    # if floor_time_score_weight == 1: floor_time_score_weight = 0.99     # To prevent all points from coinciding on the x-axis, cannot really set to 1, 0.99 is sufficient
    points = [(x * (1 - floor_time_score_weight), y) for x, y in points]
    points.append([max_x, points[-1][1]])
    prev_y, prev_x, area = start_score, 0, 0  
    max_area = max_x * max_y
    for i in range(len(points)):
        x1, y1 = points[i]
        area += (x1 - prev_x) * prev_y
        prev_x, prev_y = x1, y1
    return area / max_area


def stat_scores(input_file, start_idx=0, end_idx=None, max_score=2):
    try:
        data_list = json.load(open(input_file, 'r'))
    except:
        data_list = [json.loads(line) for line in open(input_file, 'r')]
    data_list = data_list[start_idx: end_idx]
    auc_list, immediate_score_list, rep_list = list(), list(), list()
    for example in data_list:
        for answer_turn in example['answer']:
            answer_turn['res_list'] = [res for res in answer_turn['res_list'] if res['score'] is not None]
            if answer_turn['reply_timespan'][1] - answer_turn['reply_timespan'][0] < 0.5:   # this is a one-turn reply
                if len(answer_turn['res_list']) == 0:
                    immediate_score_list.append(0.5)
                else:
                    immediate_score_list.append(answer_turn['res_list'][0]['score'])
                continue

            # calculate scores
            points = [(res['time'] - answer_turn['reply_timespan'][0], res['score']) for res in answer_turn['res_list']]
            max_x, max_y = answer_turn['reply_timespan'][1] - answer_turn['reply_timespan'][0], max_score
            auc_list.append(area_under_line_ratio(points, max_x, max_y))

            # calculate repetition
            # The repetition metric only makes sense when the model has replies
            if len(points):
                repetitions = [int(res['repetition']) for res in answer_turn['res_list'][1:]]
                rep_list.append(sum(repetitions) / len(repetitions) if len(repetitions) else 0)

    # final scores
    pauc = np.mean(auc_list)
    repetition = np.mean(rep_list) if rep_list else 0
    immediate_score = np.mean(immediate_score_list)
    print(f"score file name: {input_file}, num examples: {len(data_list)}, num answer turns: {len(auc_list)}")
    print(f"PAUC: {round(pauc * 100, 2)}; repetition: {round(repetition * 100, 2)}; immediate score: {round(immediate_score, 2)}")
    return pauc, repetition, immediate_score


def report_streamingbench(input_file, gold_file, start_idx, end_idx):
    pred_data_list = list()
    for line_i, line in enumerate(open(input_file, 'r')):
        if line_i < start_idx: continue
        if line_i == end_idx: break
        pred_data_list.append(json.loads(line))
    print('num_examples:', len(pred_data_list))
    gold_data_list = json.load(open(gold_file, 'r'))
    gold_data_dict = {e['question_id']: e for e in gold_data_list}
    interval_sec_list = list()
    for pred_data in pred_data_list:
        model_responses = [turn for turn in pred_data['model_response_list'] if turn['role'] == 'assistant']
        if not model_responses:
            interval_sec_list.append(100)
            continue
        response_time = model_responses[0]['time']
        gold_time = np.mean([gold_data_dict[pred_data['question_id']]['answer'][0]['reply_timespan'][0], gold_data_dict[pred_data['question_id']]['answer'][0]['reply_timespan'][1]])
        interval_sec_list.append(response_time - gold_time)
    print(interval_sec_list)

    interval_0s_acc = len([interval for interval in interval_sec_list if abs(interval) <= 0]) / len(interval_sec_list)
    interval_1s_acc = len([interval for interval in interval_sec_list if abs(interval) <= 1]) / len(interval_sec_list)
    interval_2s_acc = len([interval for interval in interval_sec_list if abs(interval) <= 2]) / len(interval_sec_list)
    interval_3s_acc = len([interval for interval in interval_sec_list if abs(interval) <= 3]) / len(interval_sec_list)
    print(f"{input_file=}")
    print(f"0s_acc: {interval_0s_acc}\n1s_acc: {interval_1s_acc}\n2s_acc: {interval_2s_acc}\n3s_acc: {interval_3s_acc}")


